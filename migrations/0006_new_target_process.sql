-- New target process (Nov 2026): pack sub categories.

-- Sub category of each pack (the "Pacage" column of the pack mapping file):
-- SSNR, MSPET, PMIX, Water, LIT, LRB_Other. Used for the category -> sub
-- category rows of the distribution and the Head of Department summary.
-- NULL = derived from the pack name.
ALTER TABLE packs ADD COLUMN sub TEXT;

-- Seeded from "Mapping Pack with Category SSNR-MSPET.xlsx" (packs matched
-- ignoring underscores, spaces and case). Admin can upload the mapping again.
UPDATE packs SET sub = CASE upper(replace(replace(code, '_', ''), ' ', ''))
    WHEN 'AQUAFINA330' THEN 'Water'
    WHEN 'CSDCANS330' THEN 'SSNR'
    WHEN 'LITCANS320' THEN 'LIT'
    WHEN 'AQUAFINA500' THEN 'Water'
    WHEN 'CSDPET2250' THEN 'MSPET'
    WHEN 'CSDPET1000' THEN 'MSPET'
    WHEN 'LITCANS240' THEN 'LIT'
    WHEN 'AQUAFINA1500' THEN 'Water'
    WHEN 'CSDNRB' THEN 'SSNR'
    WHEN 'AQUAFINASPARKLING250' THEN 'Water'
    WHEN 'CSDCANS150' THEN 'SSNR'
    WHEN 'GATORADE' THEN 'LRB_Other'
    WHEN 'PMIX' THEN 'PMIX'
    WHEN 'ROCKSTAR185' THEN 'LRB_Other'
    WHEN 'ROCKSTAR250' THEN 'LRB_Other'
    WHEN 'AQUAFINA200' THEN 'Water'
    WHEN 'AQUAFINANRB250' THEN 'Water'
    WHEN 'AQUAFINANRB750' THEN 'Water'
    WHEN 'BRITVIC300' THEN 'LRB_Other'
    WHEN 'BRITVICSODA' THEN 'LRB_Other'
    WHEN 'CSDCANS240' THEN 'SSNR'
    WHEN 'CSDCANS245' THEN 'SSNR'
    WHEN 'CSDCANS300' THEN 'SSNR'
    WHEN 'CSDCANS320' THEN 'SSNR'
    WHEN 'CSDCANS325' THEN 'SSNR'
    WHEN 'CSDCANS360' THEN 'SSNR'
    WHEN 'CSDPET2000' THEN 'MSPET'
    WHEN 'CSDSSPET250' THEN 'SSNR'
    WHEN 'LITCANS310' THEN 'LIT'
    WHEN 'LITCANS315' THEN 'LIT'
    WHEN 'MPLUSNRB300' THEN 'LRB_Other'
    WHEN 'STING240' THEN 'SSNR'
    WHEN 'STING250' THEN 'SSNR'
    WHEN 'STINGENERGY185' THEN 'LRB_Other'
    WHEN 'STINGENERGY240' THEN 'LRB_Other'
    WHEN 'STINGENERGY300' THEN 'LRB_Other'
    WHEN 'LITFSY' THEN 'LIT'
    WHEN 'CSDSSPET400' THEN 'SSNR'
    WHEN 'CSDSSPET500' THEN 'SSNR'
    WHEN 'AQUAFINANRB330' THEN 'Water'
    WHEN 'CSDPET2200' THEN 'MSPET'
    WHEN 'CSDCANS355' THEN 'SSNR'
    WHEN 'LITCANS150' THEN 'LIT'
  END
WHERE upper(replace(replace(code, '_', ''), ' ', '')) IN ('AQUAFINA330', 'CSDCANS330', 'LITCANS320', 'AQUAFINA500', 'CSDPET2250', 'CSDPET1000', 'LITCANS240', 'AQUAFINA1500', 'CSDNRB', 'AQUAFINASPARKLING250', 'CSDCANS150', 'GATORADE', 'PMIX', 'ROCKSTAR185', 'ROCKSTAR250', 'AQUAFINA200', 'AQUAFINANRB250', 'AQUAFINANRB750', 'BRITVIC300', 'BRITVICSODA', 'CSDCANS240', 'CSDCANS245', 'CSDCANS300', 'CSDCANS320', 'CSDCANS325', 'CSDCANS360', 'CSDPET2000', 'CSDSSPET250', 'LITCANS310', 'LITCANS315', 'MPLUSNRB300', 'STING240', 'STING250', 'STINGENERGY185', 'STINGENERGY240', 'STINGENERGY300', 'LITFSY', 'CSDSSPET400', 'CSDSSPET500', 'AQUAFINANRB330', 'CSDPET2200', 'CSDCANS355', 'LITCANS150');
